import {
  RenderToGameEventSchema,
  SceneDiffPacketSchema,
  type RenderToGameEvent,
  type SceneDiffPacket,
  type UnityUrpRenderProfile,
} from '../contracts/render-bridge.schema.ts';
import { ok, type ExwResult } from '../contracts/trigger-bus.schema.ts';
import { parseJsonBoundary, parseWithZodSchema } from './zod-boundary.parser.ts';

/**
 * [L0/L4] FUP-007 / FUP-010 | SM-05 | OPT-02 A+
 * Unity 6 URP Serialization, Event Parsing & C#/.jslib Codegen Parser.
 * Strict Result-pattern boundary between pure TypeScript simulation and Unity 6 URP runtime.
 */
export function serializeSceneDiffForUnity(packet: SceneDiffPacket): ExwResult<string> {
  const [parseErr, valid] = parseWithZodSchema(SceneDiffPacketSchema, packet, 'UnitySceneDiffPacket');
  if (parseErr !== null) return [parseErr, null];
  return ok(JSON.stringify(valid));
}

export function parseUnityToGameEvent(rawJson: string): ExwResult<RenderToGameEvent> {
  return parseJsonBoundary(RenderToGameEventSchema, rawJson, 'UnityToGameEvent');
}

